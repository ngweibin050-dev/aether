"""Write docs/CAD_RESULTS.md from a CAD run's report.json + model.aethercad (numbers are copied, never typed).

    python tools/cad_results.py <run_dir> [pytest_summary_line]
"""
import json
import sys
from pathlib import Path

run = Path(sys.argv[1])
tests = sys.argv[2] if len(sys.argv) > 2 else "not recorded"
rep = json.loads((run / "report.json").read_text())
doc = json.loads((run / "model.aethercad").read_text())
L = []
w = L.append
w("# AETHER CAD — measured results (car three-view sheet)\n")
w(f"Generated by `tools/cad_results.py` from `{run.name}/report.json` and `model.aethercad`. Every number is copied from "
  "those files. The input sheet is third-party and kept out of the repository; its hash: "
  f"`{doc['source']['sha256'][:16]}…` ({doc['source']['size_px'][0]} × {doc['source']['size_px'][1]} px).\n")
w(f"**Maturity reached:** `{rep.get('maturity_reached')}`. That is the highest level the pipeline sets by itself; "
  "`engineer_reviewed` needs a person.\n")
w(f"**CAD test suite:** {tests}\n")

# components
comps = [c for c in doc["components"] if not c.get("group")]
w("## Model\n")
w(f"- **Content:** {len(doc['features'])} features, {len(comps)} solid components, "
  f"{len([c for c in doc['components'] if c.get('group')])} assemblies (wheels), {len(doc['joints'])} joints.")
counts = rep.get("provenance_counts", {})
w("- **Parameters by provenance:** " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".")
st = [k for k in doc["parameters"] if k.endswith(".x_ref")]
w(f"- **Body:** {len(st)} cross-section stations (keypoint sketches) → one skinned B-spline surface, mirrored at the "
  "symmetry plane, planar end caps.")
w("- **Region features (accepted labels only):**")
for f in doc["features"]:
    if f["op"] in ("imprint_projection", "pocket_projection"):
        w(f"  - `{f['id']}` — {f.get('label')}")
w("")

nb = rep.get("features_not_built") or []
w("**Optional features NOT built** (they add no volume; skipped visibly because they could not meet the validity / "
  "tolerance rules): " + ("none." if not nb else ""))
for f in nb:
    w(f"- `{f['id']}` — {f['label']}: {f['why']}")
w("")

# validation
val = rep["validation"]
w("## A. Solid validity (OpenCascade)\n")
w("| component | BRepCheck | solids | faces | free edges | volume mm³ | max tolerance mm | valid |")
w("|---|---|---|---|---|---|---|---|")
for cid, r in val["components"].items():
    w(f"| {cid} | {r.get('brepcheck_valid')} | {r.get('solids')} | {r.get('faces')} | {r.get('free_edges')} | "
      f"{r.get('volume_mm3', 0):,.0f} | {r.get('max_tolerance_mm')} | **{r.get('valid')}** |")
w("")
w("**Interference / contact (pairs whose boxes overlap):**\n")
for i in val["interference"]:
    w(f"- {i['a']} × {i['b']}: {i.get('common_volume_mm3', '—')} mm³ — {i['status']}")
w("")

# STEP
rt = rep.get("step_roundtrip", {})
w("## E. STEP round trip (written, then re-read in a fresh process)\n")
if "components" in rt:
    w(f"All pass: **{rt['all_pass']}**. Missing after re-read: {rt['missing'] or 'none'}. Stated limit: "
      f"{rt['tolerance_mm']} mm, or the original B-rep's own maximum tolerance where that is larger (reported per row).\n")
    w("| component | faces (orig / re-read) | volume rel. diff | max point distance mm | limit used mm | pass |")
    w("|---|---|---|---|---|---|")
    for cid, r in rt["components"].items():
        d = max(r["dist_orig_to_reimport_mm"]["max"], r["dist_reimport_to_orig_mm"]["max"])
        w(f"| {cid} | {r['counts']['faces'][0]} / {r['counts']['faces'][1]} | {r['volume_rel_diff']:.1e} | {d:.5f} | "
          f"{r.get('tolerance_used_mm', '')} | **{r['pass']}** |")
else:
    w(f"Not run: {rt}")
w("")

# reprojection
w("## F. Three-view reprojection (B-rep projected into each view's own pixel frame)\n")
w("| view | IoU | boundary mean px (mm) | p95 px | Hausdorff px | normalised contour distance | best shift px | width / height deviation mm |")
w("|---|---|---|---|---|---|---|---|")
for v, m in rep["reprojection"].items():
    b, bm, d = m["boundary_px"], m["boundary_mm"], m.get("dims") or {}
    w(f"| {v} | {m['iou']} | {b['symmetric_mean']} ({bm['symmetric_mean']}) | {b['p95']} | {b['hausdorff']} | "
      f"{m['normalised_contour_distance']} | {m['alignment']['best_shift_px']} | {d.get('width_dev_mm')} / {d.get('height_dev_mm')} |")
w("")
w("Overlay images (grey drawing, cyan model outline, red = drawn not covered, magenta = model where nothing is drawn): "
  "`reproject_side.png`, `reproject_top.png`, `reproject_front.png`, `reproject_rear.png` in the run folder.\n")
w(f"> {rep.get('reprojection_note')}\n")
if isinstance(rep.get("S8_verification"), list):
    w("**Muse Spark S8 review of the overlays (advisory, not a pass/fail):**\n")
    for i in rep["S8_verification"]:
        w(f"- [{i['severity']}] {i['view']}: {i['description']}")
    w("")

# assumptions
w("## H. Assumptions (every one is editable)\n")
for a in rep["assumptions"]:
    w(f"- **{a['id']}** ({a['class']}): {a['text']}" + (f" — edit: {', '.join(a['editable_via'])}" if a["editable_via"] else ""))
w("")
w("## Decisions\n")
for k, d in doc["decisions"].items():
    if isinstance(d, dict):
        w(f"- `{k}` = {d.get('value')} ({d.get('provenance')}{'; ' + str(d.get('by') or d.get('note') or '') if d.get('by') or d.get('note') else ''})")
w("")
pr = doc.get("pipeline_report", {})
if pr.get("S3"):
    w("## AI stages\n")
    w("- **S3 region labels** (accepted = Muse Spark and Muse Wonder agree): " + "; ".join(
        f"{v}: " + ", ".join(f"{k} {n}" for k, n in c.items()) for v, c in pr["S3"]["counts"].items()))
if pr.get("S5"):
    w("- **S5 section hypotheses**, each built and scored by front/rear reprojection: " + "; ".join(
        f"{c['name']} {c['score_mean_iou']:.4f}" for c in pr["S5"]["candidates"]) + f" → chosen: **{pr['S5']['chosen']}**")
hyp = doc.get("hypotheses", [])
w(f"- **Stored model answers:** {len(hyp)} (replayed only for identical prompts). Models used: " + ", ".join(sorted({h.get('model', '?') for h in hyp})))
(Path(__file__).resolve().parents[1] / "docs" / "CAD_RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote docs/CAD_RESULTS.md")
